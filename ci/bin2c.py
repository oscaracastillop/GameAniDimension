import sys
import os

if len(sys.argv) < 3:
    print("Usage: python bin2c.py <input> <output>")
    sys.exit(1)

input_file = sys.argv[1]
output_file = sys.argv[2]
string_name = "bundled_font"
filename = os.path.basename(input_file)

with open(input_file, "rb") as f:
    data = f.read()

file_size = len(data)

os.makedirs(os.path.dirname(os.path.abspath(output_file)), exist_ok=True)
with open(output_file, "w", encoding="utf-8") as f:
    f.write("/* Generated by bin2c.py and should be compiled with your program.  */\n")
    f.write("/* Access with :                                                     */\n")
    f.write("/*   extern const size_t stringname_len; (excludes terminating NULL) */\n")
    f.write("/*   extern const unsigned char stringname[];                        */\n\n")
    f.write("#include <stdio.h>   /* for size_t */\n\n")
    f.write(f"/* Original filename: '{filename}' */\n")
    f.write(f"extern const char* {string_name}_name;\n")
    f.write(f"extern const size_t {string_name}_len;\n")
    f.write(f"extern const unsigned char {string_name}[];\n\n")
    f.write(f'const char* {string_name}_name = "{filename}";\n')
    f.write(f"const size_t {string_name}_len = {file_size};\n")
    f.write(f"const unsigned char {string_name}[{file_size + 1}] = {{\n")
    
    for i in range(0, file_size, 20):
        chunk = data[i:i+20]
        line = "".join(f"{b:3d}," for b in chunk)
        f.write(line + "\n")
        
    f.write("\n  0 };\n\n")

print(f"bin2c.py - Successfully written '{output_file}' ({file_size} bytes).")

